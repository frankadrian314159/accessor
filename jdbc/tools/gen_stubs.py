#!/usr/bin/env python3
"""Generates the Unsupported* base classes of the JDBC driver from the java.sql interfaces.

Each class implements every abstract method of one interface by throwing
SQLFeatureNotSupportedException, so that the real driver classes only have to override what the
driver supports. Run it again after changing the Java version the driver is built with:

    python3 tools/gen_stubs.py            (from the jdbc directory; needs javap on the PATH)
"""
import re
import subprocess
import sys
from pathlib import Path

INTERFACES = {
    "Connection": "java.sql.Connection",
    "Statement": "java.sql.Statement",
    "PreparedStatement": "java.sql.PreparedStatement",
    "ResultSet": "java.sql.ResultSet",
    "ResultSetMetaData": "java.sql.ResultSetMetaData",
    "DatabaseMetaData": "java.sql.DatabaseMetaData",
    "ParameterMetaData": "java.sql.ParameterMetaData",
}

OUT = Path(__file__).resolve().parent.parent / "src" / "main" / "java" / "com" / "accessor" / "jdbc"


def split_params(s: str):
    """Splits a parameter list at the commas that are not inside <...>."""
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def generate(short: str, full: str) -> str:
    text = subprocess.run(["javap", "-public", full], capture_output=True, text=True, check=True).stdout
    methods = []
    for line in text.splitlines():
        line = line.strip().rstrip(";")
        if not line.startswith("public abstract ") or "(" not in line:
            continue
        line = line[len("public abstract "):]
        head, rest = line.split("(", 1)
        params, tail = rest.rsplit(")", 1)
        head = head.strip()
        generics = ""
        if head.startswith("<"):
            depth = 0
            for i, ch in enumerate(head):
                depth += ch == "<"
                depth -= ch == ">"
                if depth == 0:
                    generics, head = head[: i + 1], head[i + 1:].strip()
                    break
        ret, name = head.rsplit(" ", 1)
        plist = [f"{t} a{i}" for i, t in enumerate(split_params(params))]
        throws = tail.strip()
        methods.append((generics, ret, name, ", ".join(plist), throws))
    body = []
    for generics, ret, name, plist, throws in methods:
        if name in ("unwrap", "isWrapperFor"):
            continue  # implemented once, below
        g = f"{generics} " if generics else ""
        t = f" {throws}" if throws else ""
        # A few methods (setClientInfo) cannot throw SQLException; they get an unchecked exception.
        if "SQLException" in throws:
            raise_it = f"Unsupported.feature(\"{short}.{name}\")"
        else:
            raise_it = f"new UnsupportedOperationException(\"{short}.{name} is not supported by the Accessor driver\")"
        body.append(
            f"    @Override\n    public {g}{ret} {name}({plist}){t} {{\n"
            f"        throw {raise_it};\n    }}\n"
        )
    if short == "PreparedStatement":
        # A prepared statement is a statement too, so this one builds on the driver's Statement class.
        return (
            "// GENERATED by tools/gen_stubs.py from " + full + " - do not edit.\n"
            "package com.accessor.jdbc;\n\n"
            f"/** Every method of {full} that the driver does not implement itself. */\n"
            f"abstract class Unsupported{short} extends AccessorStatement implements {full} {{\n"
            f"    Unsupported{short}(AccessorConnection conn, int resultSetType) {{\n"
            "        super(conn, resultSetType);\n    }\n\n"
            + "\n".join(body)
            + "}\n"
        )
    return (
        "// GENERATED by tools/gen_stubs.py from " + full + " - do not edit.\n"
        "package com.accessor.jdbc;\n\n"
        f"/** Every method of {full} that the driver does not implement itself. */\n"
        f"abstract class Unsupported{short} implements {full} {{\n"
        "    @Override\n    public <T> T unwrap(Class<T> type) throws java.sql.SQLException {\n"
        "        if (type.isInstance(this)) {\n            return type.cast(this);\n        }\n"
        "        throw new java.sql.SQLException(\"not a wrapper for \" + type.getName(), \"HY000\");\n    }\n\n"
        "    @Override\n    public boolean isWrapperFor(Class<?> type) {\n        return type.isInstance(this);\n    }\n\n"
        + "\n".join(body)
        + "}\n"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for short, full in INTERFACES.items():
        (OUT / f"Unsupported{short}.java").write_text(generate(short, full), encoding="utf-8", newline="\n")
        print("wrote Unsupported" + short)


if __name__ == "__main__":
    sys.exit(main())
